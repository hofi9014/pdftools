// Which characters the PDF text font can draw. Text in the tagged-PDF writer
// (lib/pdf/htmlToTaggedPdf.ts) is set in Liberation Sans as shipped with pdf.js
// (public/pdfjs-dist/standard_fonts/), which covers Latin, Greek and basic Cyrillic and nothing
// else: a character outside it is drawn as an empty box. The tools that write such a PDF say so
// before converting, listing the characters (tests/markdown-to-pdf.mts checks this list against
// the font file, all four styles have the same set).

