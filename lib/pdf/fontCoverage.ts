export function fontHasChar(cp: number): boolean {
  let lo = 0;
  let hi = RANGES.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const [a, b] = RANGES[mid]!;
    if (cp < a) hi = mid - 1;
    else if (cp > b) lo = mid + 1;
    else return true;
  }
  return false;
}

/** Distinct characters of `text` the font cannot draw, in order of appearance (at most `max`). */
export function missingGlyphs(text: string, max = 12): string[] {
  const out: string[] = [];
  const seen = new Set<string>();
  for (const ch of text) {
    if (ch === '\n' || ch === '\r' || ch === '\t' || seen.has(ch)) continue;
    seen.add(ch);
    // Joiners and variation selectors are not drawn on their own.
    const cp = ch.codePointAt(0)!;
    if (cp === 0x200D || cp === 0x200C || (cp >= 0xFE00 && cp <= 0xFE0F)) continue;
    if (!fontHasChar(cp)) {
      out.push(ch);
      if (out.length >= max) break;
    }
  }
  return out;
}
